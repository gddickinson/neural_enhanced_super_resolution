"""Precomputed super-resolution examples on synthetic test patterns (the static site's comparison slider).

For each pattern in nesr.test_patterns (256 x 256) and each factor in FACTORS:
  hr  = the pattern (ground truth)
  lr  = nesr.utils.image_utils.downsample_image(hr, 1/factor, 'bicubic')   (the GUI's degradation tool)
  out = sr_methods.run(method, lr, factor) for every method in EXAMPLE_METHODS
and PSNR / SSIM of every output against hr (nesr.metrics). PNGs and examples.json live in static/examples/.

Generated by scripts/make_examples.py; the Real-ESRGAN outputs need torch + basicsr + realesrgan, so they are made
once on a machine that has them and committed (outputs only; no new weights).
"""
import json
import os

import cv2
import numpy as np

from nesr.metrics import psnr, ssim
from nesr.test_patterns import PATTERNS, make_pattern
from nesr.utils.image_utils import downsample_image

from .sr_methods import METHODS

HERE = os.path.dirname(os.path.abspath(__file__))
EXAMPLES_DIR = os.path.join(HERE, "static", "examples")
MANIFEST = os.path.join(EXAMPLES_DIR, "examples.json")
SIZE = 256
FACTORS = (2, 4)
EXAMPLE_METHODS = ("nearest", "bicubic", "lanczos", "nesr_basic", "realesrgan", "nesr_esrgan")


def example_id(pattern, factor):
    return f"{pattern}_x{factor}"


def file_name(pattern, factor=None, what="hr"):
    return f"{pattern}_hr.png" if what == "hr" else f"{pattern}_x{factor}_{what}.png"


def make_lr(hr, factor):
    return downsample_image(hr, scale_factor=1.0 / factor, interpolation="bicubic")


def read_png(name):
    img = cv2.imread(os.path.join(EXAMPLES_DIR, name), cv2.IMREAD_COLOR)
    if img is None:
        raise FileNotFoundError(name)
    return cv2.cvtColor(img, cv2.COLOR_BGR2RGB)


def write_png(name, rgb):
    os.makedirs(EXAMPLES_DIR, exist_ok=True)
    cv2.imwrite(os.path.join(EXAMPLES_DIR, name), cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR),
                [cv2.IMWRITE_PNG_COMPRESSION, 9])


def scores(hr, out):
    return {"psnr": round(psnr(hr, out), 6), "ssim": round(ssim(hr, out), 6)}


def load_manifest():
    """The committed examples.json, or an empty manifest if it has not been generated."""
    if not os.path.exists(MANIFEST):
        return {"examples": [], "patterns": [], "methods": [], "factors": list(FACTORS), "size": SIZE}
    with open(MANIFEST, encoding="utf-8") as f:
        return json.load(f)


def pattern_list():
    return [{"id": k, "title": v[0], "description": v[1]} for k, v in PATTERNS.items()]


def method_list():
    return [{"id": m, "label": METHODS[m]["label"], "short": METHODS[m]["short"], "kind": METHODS[m]["kind"],
             "description": METHODS[m]["description"], "browser": METHODS[m]["browser"]} for m in EXAMPLE_METHODS]


def entry(pattern, factor, results):
    """Manifest entry for one example; results maps method -> {psnr, ssim, seconds?, models_loaded?}."""
    return {"id": example_id(pattern, factor), "pattern": pattern, "title": PATTERNS[pattern][0], "factor": factor,
            "size": SIZE, "lr_size": SIZE // factor, "hr": file_name(pattern), "lr": file_name(pattern, factor, "lr"),
            "outputs": {m: dict(results[m], file=file_name(pattern, factor, m)) for m in EXAMPLE_METHODS
                        if m in results}}


def hr_image(pattern):
    return make_pattern(pattern, SIZE)


def check_shapes(hr, lr, out, factor):
    assert lr.shape == (SIZE // factor, SIZE // factor, 3), lr.shape
    assert out.shape == hr.shape, (out.shape, hr.shape)
    return np.asarray(out, dtype=np.uint8)
